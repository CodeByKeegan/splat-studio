// Generates docs/CLI_COVERAGE.md — which splat-transform CLI flags the GUI wires.
// Parses the real `--help` and looks each flag up in the server command builders,
// so the table can't drift from the installed CLI. `--check` verifies it's current
// (exit 1 if stale) instead of writing.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const cli = path.join(root, 'node_modules', '@playcanvas', 'splat-transform', 'bin', 'cli.mjs');
const out = path.join(root, 'docs', 'CLI_COVERAGE.md');
const checkOnly = process.argv.includes('--check');

// Flags a GUI has no business surfacing, with the reason shown in the table.
const EXCLUDED = {
    '--help': 'CLI-only',
    '--version': 'CLI-only (the app shows its own version)',
    '--quiet': 'used internally by the summary job',
    '--tty': 'always --no-tty (output is piped to the job log)',
    '--list-gpus': 'CLI-only diagnostic'
};

if (!fs.existsSync(cli)) {
    console.error('splat-transform not installed — run npm install first.');
    process.exit(1);
}

const help = execFileSync(process.execPath, [cli, '--help'], { encoding: 'utf8' });
const version = JSON.parse(
    fs.readFileSync(path.join(root, 'node_modules', '@playcanvas', 'splat-transform', 'package.json'), 'utf8')
).version;

// Where a flag counts as "wired": the server builds every CLI invocation.
const sources = ['server/commands.mjs', 'server/index.mjs']
    .map(f => fs.readFileSync(path.join(root, f), 'utf8'))
    .join('\n');

// Sections are flush-left ALL-CAPS headings; flags are indented and start with - or --.
const sections = [];
for (const line of help.split(/\r?\n/)) {
    if (/^[A-Z]{2}/.test(line)) {
        sections.push({ title: line.split(' — ')[0].trim(), flags: [] });
        continue;
    }
    const flag = line.match(/^\s{4,}(?:(-\w), )?(--[a-z0-9-]+)\s*(<[^>]+>|\[[^\]]*\])?\s+(\S.*)$/);
    if (flag && sections.length) {
        const [, short, long, arg, desc] = flag;
        sections[sections.length - 1].flags.push({ short, long, arg: arg || '', desc: desc.trim() });
    }
}

const wired = ({ short, long }) => {
    if (long in EXCLUDED) return null;
    const hit = sources.includes(`'${long}'`) || (short && new RegExp(`'${short}'`).test(sources));
    return hit;
};

const rows = sections.flatMap(s => s.flags.map(f => ({ ...f, section: s.title })));
const counted = rows.filter(f => !(f.long in EXCLUDED));
const covered = counted.filter(f => wired(f));
const missing = counted.filter(f => !wired(f));

const md = (s) => s.replace(/\|/g, '\\|');   // pipes break table cells, even inside backticks
const text = (s) => md(s).replace(/</g, '&lt;').replace(/>/g, '&gt;');   // <n> would render as a tag

const cell = (f) => {
    const name = md(`\`${f.short ? `${f.short}, ` : ''}${f.long}${f.arg ? ` ${f.arg}` : ''}\``);
    if (f.long in EXCLUDED) return [name, '—', `not applicable to a GUI (${EXCLUDED[f.long]})`];
    return [name, wired(f) ? '✅' : '⬜', text(f.desc)];
};

const body = [
    '# CLI coverage',
    '',
    '<!-- Generated by `npm run coverage` — do not edit by hand. -->',
    '',
    `Which [\`@playcanvas/splat-transform\`](https://github.com/playcanvas/splat-transform) \`${version}\``,
    'flags the Splat Studio GUI surfaces. ✅ wired · ⬜ not yet · — not applicable.',
    '',
    `**${covered.length} of ${counted.length} applicable flags wired.**` +
        (missing.length ? ` Unwired: ${missing.map(f => `\`${f.long}\``).join(', ')}.` : ' Full coverage.'),
    '',
    'An unwired flag is a candidate for the [development routine][dev-cycle]; run the',
    '[design pass][design-pass] before wiring one — a flag is not a feature until someone',
    'works out what it is for.',
    '',
    '[dev-cycle]: https://github.com/CodeByKeegan/splat-studio/blob/dev/.agents/workflows/dev-cycle.md',
    '[design-pass]: https://github.com/CodeByKeegan/splat-studio/blob/dev/.claude/skills/splat-studio-design-pass/SKILL.md',
    ''
];

for (const s of sections.filter(s => s.flags.length)) {
    body.push(`## ${s.title}`, '', '| Flag | GUI | What it does |', '| --- | :---: | --- |');
    for (const f of s.flags) body.push(`| ${cell(f).join(' | ')} |`);
    body.push('');
}

const doc = body.join('\n');

if (checkOnly) {
    const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
    if (current !== doc) {
        console.error('docs/CLI_COVERAGE.md is stale — run `npm run coverage`.');
        process.exit(1);
    }
    console.log(`coverage table current (${covered.length}/${counted.length} flags wired).`);
} else {
    fs.writeFileSync(out, doc);
    console.log(`wrote docs/CLI_COVERAGE.md — ${covered.length}/${counted.length} flags wired` +
        (missing.length ? `, unwired: ${missing.map(f => f.long).join(', ')}` : ''));
}
